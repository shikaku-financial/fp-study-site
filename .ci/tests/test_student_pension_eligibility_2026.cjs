'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(process.argv[2]||path.resolve(__dirname,'../..'));
const ctx=vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root,'questions.js'),'utf8')+';this.audit=QUESTIONS;',ctx);
const q=id=>{const x=ctx.audit.find(item=>item.id===id);assert.ok(x,id);return x;};
const student=q('fp3-122');
assert.equal(student.answer,1);
assert.match(student.question,/本人の2025年所得 \/ 120万円/);
assert.match(student.explanation,/128万円/);
assert.match(student.explanation,/父母の所得800万円は合算しません/);
const family=q('fp2-099');
assert.equal(family.answer,0);
assert.match(family.explanation,/110万円が128万円以下/);
assert.match(family.choices[family.answer],/受給資格期間に入るが、追納しなければ老齢基礎年金額に反映されない/);
const periods=q('fp3-123');
const paid=108,studentExempt=12,unpaid=12;
assert.equal(paid+studentExempt,120);
assert.equal(paid+studentExempt+unpaid,132);
assert.equal(periods.answer,1);
assert.match(periods.explanation,/受給資格期間は120月/);
assert.match(periods.explanation,/年金額に反映するのは納付済108月/);
for(const x of [student,family,periods])assert.equal(x.lawReferenceDate,'2026-04-01');
console.log('PASS: student pension income eligibility and qualification/benefit periods agree with official 2026 JPS guidance.');
