'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(process.argv[2]||path.resolve(__dirname,'../..'));
const c=vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root,'questions.js'),'utf8')+';this.audited=QUESTIONS;',c);
const get=id=>{const q=c.audited.find(x=>x.id===id);assert.ok(q,id);return q};
const supplement=get('fp3-125');
assert.equal(200*24,4800);
assert.equal(400*24,9600);
assert.equal(supplement.answer,1);
assert.match(supplement.question,/24月/);
assert.match(supplement.question,/9,600円/);
assert.match(supplement.explanation,/4,800円/);
const early=get('fp3-127');
assert.equal(0.4*12,4.800000000000001);
assert.equal(early.choices[early.answer],'4.8');
assert.match(early.question,/1962年6月2日/);
assert.match(early.explanation,/1962年4月2日以後/);
const deferred=get('fp2-128');
assert.equal(Math.round(800000*(1+0.007*24)),934400);
assert.equal(deferred.choices[deferred.answer],'934,400円');
assert.match(deferred.explanation,/0.7％×24月/);
for(const q of [supplement,early,deferred])assert.equal(q.lawReferenceDate,'2026-04-01');
console.log('PASS: pension supplement, early pension reduction and deferred pension increase agree with official formulas.');
