'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(process.argv[2]||path.resolve(__dirname,'../..'));
const src=fs.readFileSync(path.join(root,'practical.js'),'utf8');
const found=src.match(/const completeAnswer = (.*?);\n  const grade =/s);
assert.ok(found,'missing completion predicate');
const isMulti=q=>['multi_numeric','multi_choice','wordbank_number'].includes(q.kind);
const blank=v=>v===null||v===undefined||v==='';
const numericParser=q=>v=>(typeof v==='string'&&/^[+-]?(?:\d+\.?\d*|\.\d+)$/.test(v.trim()))?Number(v):NaN;
const completeAnswer=new Function('isMulti','blank','numericParser',`return ${found[1]};`)(isMulti,blank,numericParser);
const multi={kind:'multi_numeric',subAnswers:[{kind:'numeric'},{kind:'numeric'}]};
assert.equal(completeAnswer(multi,['100','200']),true);
assert.equal(completeAnswer(multi,['100','oops']),false);
assert.equal(completeAnswer(multi,['100','']),false);
const choice={kind:'multi_choice',subAnswers:[{kind:'choice',choices:['a','b']},{kind:'choice',choices:['x','y']}]};
assert.equal(completeAnswer(choice,[0,1]),true);
assert.equal(completeAnswer(choice,[0,8]),false);
const words={kind:'wordbank_number',subAnswers:[{kind:'numeric'},{kind:'numeric'}]};
assert.equal(completeAnswer(words,['1','invalid']),false);
console.log('PASS: multi numeric and wordbank inputs require valid parsed values; multi choice indices must be in range.');
