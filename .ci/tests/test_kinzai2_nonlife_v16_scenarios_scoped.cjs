const round=x=>Math.floor(x+.5);
assert.equal(get(1).answer,round(847300*450/480));
assert.equal(get(2).answer,round(280000*7.125/1000*36+420000*5.481/1000*270));
assert.equal(get(3).choices[get(3).answer],'①×・②○・③○');
